# 十神速查表：SHISHEN_RELATION[日干][他干] = 十神名
# 构建规则：同五行→比劫，生我→印，我生→食伤，克我→官杀，我克→财
def _build_shishen_table():
    """构建十神关系速查表"""
    table = {}
    for ri_gan in GAN:
        table[ri_gan] = {}
        ri_wx = GAN_WUXING[ri_gan]
        ri_yy = GAN_YINYANG[ri_gan]
        for ta_gan in GAN:
            ta_wx = GAN_WUXING[ta_gan]
            ta_yy = GAN_YINYANG[ta_gan]
            same_yy = (ri_yy == ta_yy)

            if ri_wx == ta_wx:
                # 同五行：比肩（同阴阳）或劫财（异阴阳）
                table[ri_gan][ta_gan] = "比肩" if same_yy else "劫财"
            elif WUXING_SHENG[ri_wx] == ta_wx:
                # 生我者：正印（异阴阳）或偏印（同阴阳）
                table[ri_gan][ta_gan] = "偏印" if same_yy else "正印"
            elif WUXING_SHENG_BY[ri_wx] == ta_wx:
                # 我生者：食神（同阴阳）或伤官（异阴阳）
                table[ri_gan][ta_gan] = "食神" if same_yy else "伤官"
            elif WUXING_KE[ri_wx] == ta_wx:
                # 克我者：七杀（同阴阳）或正官（异阴阳）
                table[ri_gan][ta_gan] = "七杀" if same_yy else "正官"
            elif WUXING_KE_BY[ri_wx] == ta_wx:
                # 我克者：偏财（同阴阳）或正财（异阴阳）
                table[ri_gan][ta_gan] = "偏财" if same_yy else "正财"
    return table

SHISHEN_RELATION = _build_shishen_table()

